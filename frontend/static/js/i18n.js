// Current language
let currentLang = 'en';

// Get translation function
window.t = function(key) {
  const trans = translations[currentLang] || translations['en'];
  return trans[key] || translations['en'][key] || key;
};

// Translate page function
function translatePage() {
  const trans = translations[currentLang] || translations['en'];
  const fallback = translations['en'];
  
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = trans[key] || fallback[key] || key;
    el.textContent = text;
  });
  
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const text = trans[key] || fallback[key] || key;
    el.placeholder = text;
  });
  
  document.documentElement.lang = currentLang;
}

// Toggle language function
function toggleLang() {
  currentLang = currentLang === 'en' ? 'ga' : 'en';
  
  const toggle = document.querySelector('.lang-toggle');
  if (toggle) {
    if (currentLang === 'ga') {
      toggle.classList.add('gaelic');
    } else {
      toggle.classList.remove('gaelic');
    }
  }
  
  translatePage();
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang: currentLang } }));
}

// Initialize
document.addEventListener('DOMContentLoaded', function() {
  currentLang = 'en';
  
  const toggle = document.querySelector('.lang-toggle');
  if (toggle) {
    toggle.classList.remove('gaelic');
  }
  
  translatePage();
  
  if (toggle) {
    toggle.addEventListener('click', toggleLang);
  }
});
